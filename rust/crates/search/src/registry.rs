#[cfg(test)]
mod tests {
    use serde_json::json;
    use uuid::Uuid;

    use super::{
        RegistryError, canonical_snapshot_sha256, parse_build_request, parse_generation_request,
    };

    #[test]
    fn canonical_snapshot_checksum_ignores_object_key_order() {
        let first = json!({"pages":[{"content":"Hello","id":"p","kind":"PAGE"}],"x":1});
        let second = json!({"x":1,"pages":[{"kind":"PAGE","id":"p","content":"Hello"}]});
        assert_eq!(
            canonical_snapshot_sha256(&first),
            canonical_snapshot_sha256(&second)
        );
    }

    #[test]
    fn publication_request_payload_is_strict_and_has_no_generation_id() -> Result<(), RegistryError>
    {
        let payload = json!({
            "project_id":"project-a",
            "deployment_id":"deployment-a",
            "snapshot_sha256":"a4d9c590cfb4bb4c7fe3eaa7f58b9bb21e7e32eea7ad5016e7c563b95f6cfc20"
        });
        let request = parse_generation_request(&payload)?;
        assert_eq!(request.project_id, "project-a");
        assert!(matches!(
            parse_generation_request(&json!({
                "generation_id": Uuid::now_v7(),
                "project_id":"project-a",
                "deployment_id":"deployment-a",
                "snapshot_sha256":"a4d9c590cfb4bb4c7fe3eaa7f58b9bb21e7e32eea7ad5016e7c563b95f6cfc20"
            })),
            Err(RegistryError::InvalidRequest(_))
        ));
        Ok(())
    }

    #[test]
    fn build_payload_is_strict_and_tenant_binding_stays_outside_payload()
    -> Result<(), RegistryError> {
        let generation_id = Uuid::now_v7();
        let payload = json!({
            "generation_id": generation_id,
            "project_id":"project-a",
            "deployment_id":"deployment-a",
            "snapshot_sha256":"a4d9c590cfb4bb4c7fe3eaa7f58b9bb21e7e32eea7ad5016e7c563b95f6cfc20"
        });
        let request = parse_build_request(&payload)?;
        assert_eq!(request.generation_id, generation_id);
        assert!(matches!(
            parse_build_request(&json!({"generation_id": generation_id})),
            Err(RegistryError::InvalidRequest(_))
        ));
        Ok(())
    }
}
