//! Durable PostgreSQL lifecycle for project-local index generations.
//!
//! The registry is intentionally separate from query execution: it leases a
//! named immutable generation, lets a worker build outside a database
//! transaction, validates the manifest, and atomically advances one project's
//! active-generation pointer. It is at-least-once work; a lease token fences a
//! crashed or slow prior worker from promoting after a reclaim.

use std::{path::Path, time::Duration};

pub use nibleaf_core::canonical_json_sha256 as canonical_snapshot_sha256;
use serde_json::Value;
use sqlx::{FromRow, PgPool, Postgres, Transaction};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::{
    DocumentDigest, GenerationManifest, SearchDocument, SearchError, build_generation,
    discard_staging_generation, documents_digest, generation_directory, open_generation,
    snapshot::snapshot_documents, validate_generation,
};

/// Offline, read-only operator input validation using the same typed extractor
/// as durable builds. Hash and query input ceilings are checked before creating
/// an output root. This is not publication/promotion authority.
/// # Errors
/// Refuses modified snapshots, malformed scope/source or oversized corpora.
pub fn verified_snapshot_documents(
    snapshot: &Value,
    project: &str,
    expected_sha256: &str,
    config: crate::SearchQueryConfig,
) -> Result<Vec<SearchDocument>, RegistryError> {
    if canonical_snapshot_sha256(snapshot) != expected_sha256 {
        return Err(RegistryError::Snapshot("snapshot binding mismatch"));
    }
    let documents = snapshot_documents(snapshot, project)?;
    if documents.len() > config.max_documents {
        return Err(SearchError::ResourceLimit("offline document count").into());
    }
    let bytes = documents.iter().try_fold(0_usize, |sum, doc| {
        sum.checked_add(crate::document_text_bytes(doc))
    });
    if bytes.is_none_or(|bytes| bytes > config.max_source_bytes) {
        return Err(SearchError::ResourceLimit("offline source bytes").into());
    }
    Ok(documents)
}

/// Internal identity for one registry-assigned generation build. The worker
/// obtains it only after it has rechecked the publication-owned request against
/// PostgreSQL and persisted/reused the matching row; no queue payload is
/// accepted as authority without that tenant relation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SearchBuildRequest {
    pub generation_id: Uuid,
    pub project_id: String,
    pub deployment_id: String,
    pub snapshot_sha256: String,
}

/// Immutable deployment identity carried by the publication-owned outbox event
/// before the search feature assigns a generation UUID in its own registry.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SearchGenerationRequest {
    pub project_id: String,
    pub deployment_id: String,
    pub snapshot_sha256: String,
}

/// A lease for the one registry row a worker may build or promote. Its token is
/// generated by PostgreSQL for every claim, including a same-worker reclaim.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ClaimedGeneration {
    pub request: SearchBuildRequest,
    pub tenant_id: String,
    pub attempt: i32,
    pub reclaimed: bool,
    pub lease_token: Uuid,
    pub leased_until: OffsetDateTime,
}

/// The registry state returned when a redelivered event needs no work.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ClaimOutcome {
    Claimed(ClaimedGeneration),
    AlreadyReady,
}

/// Classifies a build failure for the caller's durable delivery mechanism.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FailureClass {
    Permanent,
    Retryable,
}

#[derive(Debug, thiserror::Error)]
pub enum RegistryError {
    #[error("search generation request is invalid: {0}")]
    InvalidRequest(&'static str),
    #[error("search generation registry row was not found")]
    Missing,
    #[error("search generation is actively leased by another worker")]
    Busy,
    #[error("search generation lease was lost")]
    LeaseLost,
    #[error("search generation has terminally failed")]
    Terminal,
    #[error("search deployment snapshot is invalid: {0}")]
    Snapshot(&'static str),
    #[error("search generation cannot be promoted: {0}")]
    Promotion(&'static str),
    #[error("search generation index failure")]
    Search(#[from] SearchError),
    #[error("search generation database operation failed")]
    Database(#[from] sqlx::Error),
    #[error("search generation build configuration is invalid")]
    BuildConfiguration,
    #[error("search generation build task failed")]
    BuildTask,
}

impl RegistryError {
    /// Returns the durable-delivery classification. Input/snapshot/integrity
    /// defects need an operator/new generation; database, lease, and storage
    /// failures remain retryable under a fresh claim.
    #[must_use]
    pub fn failure_class(&self) -> FailureClass {
        match self {
            Self::InvalidRequest(_)
            | Self::Missing
            | Self::Terminal
            | Self::Snapshot(_)
            | Self::Promotion(_)
            | Self::BuildConfiguration => FailureClass::Permanent,
            Self::Search(error) => match error {
                SearchError::Distribution(_)
                | SearchError::Storage(_)
                | SearchError::Tantivy(_)
                | SearchError::Cancelled
                | SearchError::Deadline
                | SearchError::ResourceLimit(_) => FailureClass::Retryable,
                SearchError::InvalidInput(_)
                | SearchError::Integrity(_)
                | SearchError::Manifest(_)
                | SearchError::Query(_)
                | SearchError::Tokenizer(_) => FailureClass::Permanent,
            },
            Self::Busy | Self::LeaseLost | Self::Database(_) | Self::BuildTask => {
                FailureClass::Retryable
            }
        }
    }

    /// Fixed, bounded diagnostics suitable for the registry row and a dead
    /// letter. The original error remains in worker logs, not database/API text.
    #[must_use]
    pub fn stable_code(&self) -> &'static str {
        match self {
            Self::InvalidRequest(_) => "invalid_build_request",
            Self::Missing => "generation_missing",
            Self::Busy => "generation_busy",
            Self::LeaseLost => "generation_lease_lost",
            Self::Terminal => "generation_terminal",
            Self::Snapshot(_) => "invalid_deployment_snapshot",
            Self::Promotion(_) => "generation_promotion_rejected",
            Self::BuildConfiguration => "generation_build_configuration_invalid",
            Self::Search(_) => "generation_index_failure",
            Self::Database(_) => "generation_database_failure",
            Self::BuildTask => "generation_build_task_failed",
        }
    }
}

/// Parses the publication-owned v1 request that starts native index work. A
/// generation ID is intentionally absent: the search registry assigns it only
/// after it checks the deployment/project/tenant relation in PostgreSQL.
///
/// # Errors
/// Returns an error for missing, oversized, malformed, or non-canonical fields.
pub fn parse_generation_request(payload: &Value) -> Result<SearchGenerationRequest, RegistryError> {
    let object = payload
        .as_object()
        .ok_or(RegistryError::InvalidRequest("payload must be an object"))?;
    if object.len() != 3 {
        return Err(RegistryError::InvalidRequest(
            "payload must contain exactly project, deployment, and snapshot identity",
        ));
    }
    let project_id = required_identifier(object.get("project_id"), "project_id")?;
    let deployment_id = required_identifier(object.get("deployment_id"), "deployment_id")?;
    let snapshot_sha256 = required_snapshot_checksum(object.get("snapshot_sha256"))?;
    Ok(SearchGenerationRequest {
        project_id,
        deployment_id,
        snapshot_sha256,
    })
}

/// Parses the typed v1 internal build payload. It remains available for a
/// reviewed operator/rebuild producer, but ordinary publication uses
/// [`parse_generation_request`] so the search feature owns generation-ID
/// allocation.
///
/// # Errors
/// Returns an error for missing, oversized, malformed, or non-canonical fields.
pub fn parse_build_request(payload: &Value) -> Result<SearchBuildRequest, RegistryError> {
    let object = payload
        .as_object()
        .ok_or(RegistryError::InvalidRequest("payload must be an object"))?;
    if object.len() != 4 {
        return Err(RegistryError::InvalidRequest(
            "payload must contain exactly generation, project, deployment, and snapshot identity",
        ));
    }
    let generation_id = object
        .get("generation_id")
        .and_then(Value::as_str)
        .ok_or(RegistryError::InvalidRequest("generation_id is required"))
        .and_then(|value| {
            Uuid::parse_str(value)
                .map_err(|_| RegistryError::InvalidRequest("generation_id is invalid"))
        })?;
    let project_id = required_identifier(object.get("project_id"), "project_id")?;
    let deployment_id = required_identifier(object.get("deployment_id"), "deployment_id")?;
    let snapshot_sha256 = required_snapshot_checksum(object.get("snapshot_sha256"))?;
    Ok(SearchBuildRequest {
        generation_id,
        project_id,
        deployment_id,
        snapshot_sha256,
    })
}

/// Registers an immutable-generation build inside the caller's existing
/// transaction. The caller must append the matching outbox event before that
/// transaction commits; this function deliberately does not own a queue.
/// Redelivery for the same deployment returns the original generation request.
///
/// # Errors
/// Returns an error if the tenant/project/deployment binding is invalid, the
/// snapshot checksum differs from an existing row, or PostgreSQL fails.
pub async fn register_generation_build(
    transaction: &mut Transaction<'_, Postgres>,
    tenant_id: &str,
    project_id: &str,
    deployment_id: &str,
    snapshot_sha256: &str,
) -> Result<SearchBuildRequest, RegistryError> {
    register_generation_build_for_delivery(
        transaction,
        tenant_id,
        project_id,
        deployment_id,
        snapshot_sha256,
        crate::distribution::DeliveryKind::Local,
    )
    .await
}

/// Same tenant/snapshot registration for an explicit server-captured delivery.
/// # Errors
/// Refuses a different deployment delivery target rather than falling back.
pub async fn register_generation_build_for_delivery(
    transaction: &mut Transaction<'_, Postgres>,
    tenant_id: &str,
    project_id: &str,
    deployment_id: &str,
    snapshot_sha256: &str,
    delivery: crate::distribution::DeliveryKind,
) -> Result<SearchBuildRequest, RegistryError> {
    validate_identifier(tenant_id, "tenant_id")?;
    validate_identifier(project_id, "project_id")?;
    validate_identifier(deployment_id, "deployment_id")?;
    if !is_sha256_hex(snapshot_sha256) {
        return Err(RegistryError::InvalidRequest(
            "snapshot_sha256 must be lowercase SHA-256 hex",
        ));
    }

    let project_tenant: Option<(String, String)> = sqlx::query_as(
        r#"
        SELECT p."organizationId", d.rust_search_delivery_mode
        FROM project AS p
        INNER JOIN deployment AS d ON d.id = $2 AND d."projectId" = p.id
        WHERE p.id = $1
        FOR SHARE
        "#,
    )
    .bind(project_id)
    .bind(deployment_id)
    .fetch_optional(&mut **transaction)
    .await?;
    if project_tenant
        .as_ref()
        .is_none_or(|(tenant, mode)| tenant != tenant_id || mode != delivery.as_str())
    {
        return Err(RegistryError::Missing);
    }

    let existing = sqlx::query_as::<_, RegistryRequestRow>(
        r"
        SELECT generation_id, project_id, deployment_id, snapshot_sha256
        FROM rust_search_generation
        WHERE project_id = $1 AND deployment_id = $2
        FOR UPDATE
        ",
    )
    .bind(project_id)
    .bind(deployment_id)
    .fetch_optional(&mut **transaction)
    .await?;
    if let Some(existing) = existing {
        if existing.snapshot_sha256 != snapshot_sha256 {
            return Err(RegistryError::Promotion(
                "deployment snapshot identity changed after registration",
            ));
        }
        return Ok(SearchBuildRequest {
            generation_id: existing.generation_id,
            project_id: existing.project_id,
            deployment_id: existing.deployment_id,
            snapshot_sha256: existing.snapshot_sha256,
        });
    }

    let request = SearchBuildRequest {
        generation_id: Uuid::now_v7(),
        project_id: project_id.to_owned(),
        deployment_id: deployment_id.to_owned(),
        snapshot_sha256: snapshot_sha256.to_owned(),
    };
    sqlx::query(
        r"
        INSERT INTO rust_search_generation (
            generation_id, project_id, deployment_id, tenant_id, snapshot_sha256, delivery_kind,
            state, attempts, created_at, updated_at
        ) VALUES ($1, $2, $3, $4, $5, $6, 'pending', 0, NOW(), NOW())
        ",
    )
    .bind(request.generation_id)
    .bind(&request.project_id)
    .bind(&request.deployment_id)
    .bind(tenant_id)
    .bind(&request.snapshot_sha256)
    .bind(delivery.as_str())
    .execute(&mut **transaction)
    .await?;
    Ok(request)
}

/// Leases a pending or expired generation build. A valid redelivery of an
/// already-ready generation is an idempotent no-op. The row identity, its
/// deployment/project relation, and its tenant are all revalidated under lock.
///
/// # Errors
/// Returns [`RegistryError::Busy`] while another lease remains live and a
/// classified error for foreign/malformed/terminal work.
pub async fn claim_generation_build(
    pool: &PgPool,
    request: &SearchBuildRequest,
    event_tenant_id: Option<&str>,
    worker_id: &str,
    lease_for: Duration,
) -> Result<ClaimOutcome, RegistryError> {
    validate_request(request)?;
    let tenant_id = event_tenant_id.ok_or(RegistryError::InvalidRequest(
        "search build event must be tenant-scoped",
    ))?;
    validate_identifier(tenant_id, "tenant_id")?;
    validate_identifier(worker_id, "worker_id")?;
    let lease_seconds = i32::try_from(lease_for.as_secs())
        .ok()
        .filter(|seconds| (30..=3_600).contains(seconds))
        .ok_or(RegistryError::InvalidRequest(
            "search build lease must be between 30 seconds and one hour",
        ))?;

    let mut transaction = pool.begin().await?;
    let row = sqlx::query_as::<_, LockedGenerationRow>(
        r#"
        SELECT g.project_id, g.deployment_id, g.tenant_id, g.snapshot_sha256,
               g.state, COALESCE(g.leased_until > NOW(), FALSE) AS lease_is_live,
               d.status::text AS deployment_status
        FROM rust_search_generation AS g
        INNER JOIN project AS p
          ON p.id = g.project_id AND p."organizationId" = g.tenant_id
        INNER JOIN deployment AS d
          ON d.id = g.deployment_id AND d."projectId" = g.project_id
        WHERE g.generation_id = $1
        FOR UPDATE
        "#,
    )
    .bind(request.generation_id)
    .fetch_optional(&mut *transaction)
    .await?
    .ok_or(RegistryError::Missing)?;
    if row.project_id != request.project_id
        || row.deployment_id != request.deployment_id
        || row.snapshot_sha256 != request.snapshot_sha256
        || row.tenant_id != tenant_id
    {
        return Err(RegistryError::InvalidRequest(
            "event identity does not match the durable generation row",
        ));
    }
    if row.deployment_status == "FAILED" {
        return Err(RegistryError::Terminal);
    }
    match row.state.as_str() {
        "ready" | "superseded" => {
            transaction.commit().await?;
            return Ok(ClaimOutcome::AlreadyReady);
        }
        "failed" => return Err(RegistryError::Terminal),
        "building" if row.lease_is_live => return Err(RegistryError::Busy),
        "pending" | "building" => {}
        _ => return Err(RegistryError::Promotion("unknown generation state")),
    }
    let reclaimed = row.state == "building";
    let claimed = sqlx::query_as::<_, ClaimedGenerationRow>(
        r"
        UPDATE rust_search_generation
        SET state = 'building', attempts = attempts + 1, lease_token = gen_random_uuid(),
            leased_until = NOW() + make_interval(secs => $2), worker_id = $3,
            last_error = NULL, updated_at = NOW()
        WHERE generation_id = $1
        RETURNING generation_id, project_id, deployment_id, tenant_id, snapshot_sha256,
                  attempts, lease_token, leased_until
        ",
    )
    .bind(request.generation_id)
    .bind(lease_seconds)
    .bind(worker_id)
    .fetch_one(&mut *transaction)
    .await?;
    transaction.commit().await?;
    Ok(ClaimOutcome::Claimed(ClaimedGeneration {
        request: SearchBuildRequest {
            generation_id: claimed.generation_id,
            project_id: claimed.project_id,
            deployment_id: claimed.deployment_id,
            snapshot_sha256: claimed.snapshot_sha256,
        },
        tenant_id: claimed.tenant_id,
        attempt: claimed.attempts,
        reclaimed,
        lease_token: claimed.lease_token,
        leased_until: claimed.leased_until,
    }))
}

/// Renews a live lease without changing its token. A caller that gets
/// [`RegistryError::LeaseLost`] must stop build/promotion work; a newer worker
/// now owns the row.
///
/// # Errors
/// Returns an error for invalid duration, database failure, or a lost lease.
pub async fn renew_generation_lease(
    pool: &PgPool,
    claim: &ClaimedGeneration,
    lease_for: Duration,
) -> Result<(), RegistryError> {
    let lease_seconds = i32::try_from(lease_for.as_secs())
        .ok()
        .filter(|seconds| (30..=3_600).contains(seconds))
        .ok_or(RegistryError::InvalidRequest(
            "search build lease must be between 30 seconds and one hour",
        ))?;
    let updated = sqlx::query(
        r"
        UPDATE rust_search_generation
        SET leased_until = NOW() + make_interval(secs => $3), updated_at = NOW()
        WHERE generation_id = $1 AND state = 'building' AND lease_token = $2
        ",
    )
    .bind(claim.request.generation_id)
    .bind(claim.lease_token)
    .bind(lease_seconds)
    .execute(pool)
    .await?;
    if updated.rows_affected() != 1 {
        return Err(RegistryError::LeaseLost);
    }
    Ok(())
}

/// Loads the immutable deployment snapshot after a worker has claimed its
/// generation. It verifies the durable snapshot checksum and exact project
/// binding before parsing the format-2 version/language/visibility contract.
/// Only enabled, visible, indexable `PAGE` records become search documents.
///
/// # Errors
/// Returns an error when the claim no longer matches the deployment, the stored
/// snapshot changed/corrupted, or a searchable page has malformed fields.
pub async fn load_claimed_snapshot_documents(
    pool: &PgPool,
    claim: &ClaimedGeneration,
) -> Result<Vec<SearchDocument>, RegistryError> {
    let snapshot: Option<Value> = sqlx::query_scalar(
        r#"
        SELECT d.snapshot
        FROM deployment AS d
        INNER JOIN project AS p ON p.id = d."projectId"
        WHERE d.id = $1 AND d."projectId" = $2 AND p."organizationId" = $3
        "#,
    )
    .bind(&claim.request.deployment_id)
    .bind(&claim.request.project_id)
    .bind(&claim.tenant_id)
    .fetch_optional(pool)
    .await?
    .flatten();
    let snapshot = snapshot.ok_or(RegistryError::Snapshot("snapshot is missing"))?;
    if canonical_snapshot_sha256(&snapshot) != claim.request.snapshot_sha256 {
        return Err(RegistryError::Snapshot(
            "snapshot checksum does not match durable build identity",
        ));
    }
    snapshot_documents(&snapshot, &claim.request.project_id)
}

/// Builds or validates a claimed generation without a PostgreSQL transaction.
/// A reclaimed worker removes only its fenced staging directory. If the final
/// immutable path already exists, it is reused only after manifest validation
/// proves it matches the exact document digest derived from the deployment.
///
/// # Errors
/// Returns a permanent error for a corrupt/mismatched final generation and a
/// retryable storage/Tantivy error for an incomplete build.
pub fn build_or_reuse_claimed_generation(
    index_root: &Path,
    claim: &ClaimedGeneration,
    documents: &[SearchDocument],
) -> Result<GenerationManifest, RegistryError> {
    let expected = documents_digest(documents)?;
    let directory = generation_directory(
        index_root,
        &claim.request.project_id,
        claim.request.generation_id,
    );
    let generation = if directory.exists() {
        let generation = open_generation(
            index_root,
            &claim.request.project_id,
            &claim.request.deployment_id,
            claim.request.generation_id,
        )?;
        let manifest = validate_generation(&generation)?;
        ensure_manifest_matches_documents(&manifest, &expected)?;
        return Ok(manifest);
    } else {
        // A claim is either first ownership or a fenced reclaim. In both cases
        // its private staging path cannot be a publishable generation and may
        // safely be cleared before beginning a clean deterministic build.
        discard_staging_generation(
            index_root,
            &claim.request.project_id,
            claim.request.generation_id,
        )?;
        build_generation(
            index_root,
            &claim.request.project_id,
            &claim.request.deployment_id,
            claim.request.generation_id,
            documents,
        )?
    };
    let manifest = validate_generation(&generation)?;
    ensure_manifest_matches_documents(&manifest, &expected)?;
    Ok(manifest)
}

/// Releases a claimed row following a build failure. Retryable failures return
/// it to `pending` for a fresh outbox delivery; permanent failures preserve an
/// operator-visible `failed` record. A stale claimant cannot alter newer work.
///
/// # Errors
/// Returns a lost-lease error when a newer worker owns the row.
pub async fn record_claim_failure(
    pool: &PgPool,
    claim: &ClaimedGeneration,
    error: &RegistryError,
) -> Result<(), RegistryError> {
    let state = match error.failure_class() {
        FailureClass::Permanent => "failed",
        FailureClass::Retryable => "pending",
    };
    let updated = sqlx::query(
        r"
        UPDATE rust_search_generation
        SET state = $3, lease_token = NULL, leased_until = NULL,
            worker_id = NULL, last_error = $4,
            completed_at = CASE WHEN $3 = 'failed' THEN NOW() ELSE NULL END,
            updated_at = NOW()
        WHERE generation_id = $1 AND state = 'building' AND lease_token = $2
        ",
    )
    .bind(claim.request.generation_id)
    .bind(claim.lease_token)
    .bind(state)
    .bind(error.stable_code())
    .execute(pool)
    .await?;
    if updated.rows_affected() != 1 {
        return Err(RegistryError::LeaseLost);
    }
    Ok(())
}

/// Atomically marks a validated claimed generation ready and switches the one
/// project pointer. Any prior active generation becomes `superseded` but its
/// on-disk data is retained; no failed/reclaimed build can replace it.
///
/// # Errors
/// Returns [`RegistryError::LeaseLost`] when promotion was reclaimed. Repeating
/// a delivery after this generation is already ready is harmless and does not
/// re-activate a historical superseded generation.
pub async fn promote_claimed_generation(
    pool: &PgPool,
    claim: &ClaimedGeneration,
    manifest: &GenerationManifest,
) -> Result<(), RegistryError> {
    promote_inner(pool, claim, manifest, None).await
}

/// Fenced object promotion: attach verified immutable provider evidence in the
/// SAME transaction that advances READY and the active pointer.
/// # Errors
/// A stale/unconfirmed/conflicting artifact cannot become reader authority.
pub async fn promote_claimed_generation_with_artifact(
    pool: &PgPool,
    claim: &ClaimedGeneration,
    manifest: &GenerationManifest,
    artifact: &crate::distribution::ArtifactReference,
) -> Result<(), RegistryError> {
    promote_inner(pool, claim, manifest, Some(artifact)).await
}

async fn promote_inner(
    pool: &PgPool,
    claim: &ClaimedGeneration,
    manifest: &GenerationManifest,
    artifact: Option<&crate::distribution::ArtifactReference>,
) -> Result<(), RegistryError> {
    validate_manifest_for_claim(manifest, claim)?;
    let document_count = i32::try_from(manifest.document_count).map_err(|_| {
        RegistryError::Promotion("document count exceeds PostgreSQL integer bounds")
    })?;
    let mut transaction = pool.begin().await?;
    let state: Option<(String,String)> = sqlx::query_as(
        "SELECT state,delivery_kind FROM rust_search_generation WHERE generation_id = $1 FOR UPDATE",
    )
    .bind(claim.request.generation_id)
    .fetch_optional(&mut *transaction)
    .await?;
    match state.as_ref().map(|(state, _)| state.as_str()) {
        Some("ready" | "superseded") => {
            transaction.commit().await?;
            return Ok(());
        }
        Some("building") => {}
        Some("pending" | "failed") | None => return Err(RegistryError::LeaseLost),
        Some(_) => return Err(RegistryError::Promotion("unknown generation state")),
    }
    let delivery = state
        .as_ref()
        .map(|(_, mode)| mode.as_str())
        .ok_or(RegistryError::Missing)?;
    match (delivery, artifact) {
        ("object", Some(artifact)) => {
            crate::distribution::catalog::attach(&mut transaction, claim, manifest, artifact)
                .await?;
        }
        ("local", None) => {}
        _ => {
            return Err(RegistryError::Promotion(
                "delivery requires matching verified artifact",
            ));
        }
    }
    let transitioned = sqlx::query(
        r"
        UPDATE rust_search_generation
        SET state = 'ready', document_count = $3, documents_sha256 = $4,
            lease_token = NULL, leased_until = NULL, worker_id = NULL,
            last_error = NULL, completed_at = NOW(), updated_at = NOW()
        WHERE generation_id = $1 AND state = 'building' AND lease_token = $2
        ",
    )
    .bind(claim.request.generation_id)
    .bind(claim.lease_token)
    .bind(document_count)
    .bind(&manifest.documents_sha256)
    .execute(&mut *transaction)
    .await?;
    if transitioned.rows_affected() != 1 {
        return Err(RegistryError::LeaseLost);
    }
    let prior: Option<Uuid> = sqlx::query_scalar(
        "SELECT generation_id FROM rust_search_active_generation WHERE project_id = $1 FOR UPDATE",
    )
    .bind(&claim.request.project_id)
    .fetch_optional(&mut *transaction)
    .await?;
    sqlx::query(
        r"
        INSERT INTO rust_search_active_generation (project_id, generation_id, activated_at, updated_at)
        VALUES ($1, $2, NOW(), NOW())
        ON CONFLICT (project_id) DO UPDATE
        SET generation_id = EXCLUDED.generation_id, activated_at = NOW(), updated_at = NOW()
        ",
    )
    .bind(&claim.request.project_id)
    .bind(claim.request.generation_id)
    .execute(&mut *transaction)
    .await?;
    if let Some(prior) = prior.filter(|prior| *prior != claim.request.generation_id) {
        sqlx::query(
            r"
            UPDATE rust_search_generation
            SET state = 'superseded', updated_at = NOW()
            WHERE generation_id = $1 AND state = 'ready'
            ",
        )
        .bind(prior)
        .execute(&mut *transaction)
        .await?;
    }
    transaction.commit().await?;
    Ok(())
}

fn ensure_manifest_matches_documents(
    manifest: &GenerationManifest,
    expected: &DocumentDigest,
) -> Result<(), RegistryError> {
    if manifest.document_count != expected.document_count
        || manifest.documents_sha256 != expected.documents_sha256
    {
        return Err(RegistryError::Promotion(
            "final generation does not match deployment documents",
        ));
    }
    Ok(())
}

fn validate_manifest_for_claim(
    manifest: &GenerationManifest,
    claim: &ClaimedGeneration,
) -> Result<(), RegistryError> {
    crate::validate_manifest_runtime(manifest)?;
    if manifest.generation_id != claim.request.generation_id
        || manifest.project_id != claim.request.project_id
        || manifest.deployment_id != claim.request.deployment_id
        || !is_sha256_hex(&manifest.documents_sha256)
    {
        return Err(RegistryError::Promotion(
            "manifest identity is not promotable for the claim",
        ));
    }
    Ok(())
}

fn validate_request(request: &SearchBuildRequest) -> Result<(), RegistryError> {
    validate_identifier(&request.project_id, "project_id")?;
    validate_identifier(&request.deployment_id, "deployment_id")?;
    if !is_sha256_hex(&request.snapshot_sha256) {
        return Err(RegistryError::InvalidRequest(
            "snapshot_sha256 must be lowercase SHA-256 hex",
        ));
    }
    Ok(())
}

fn required_identifier(value: Option<&Value>, name: &'static str) -> Result<String, RegistryError> {
    let value = value
        .and_then(Value::as_str)
        .ok_or(RegistryError::InvalidRequest(
            "required identifier is missing",
        ))?;
    validate_identifier(value, name)?;
    Ok(value.to_owned())
}

fn required_snapshot_checksum(value: Option<&Value>) -> Result<String, RegistryError> {
    value
        .and_then(Value::as_str)
        .filter(|value| is_sha256_hex(value))
        .map(ToOwned::to_owned)
        .ok_or(RegistryError::InvalidRequest(
            "snapshot_sha256 must be lowercase SHA-256 hex",
        ))
}

fn validate_identifier(value: &str, _name: &'static str) -> Result<(), RegistryError> {
    if value.is_empty() || value.len() > 191 || value.trim() != value {
        return Err(RegistryError::InvalidRequest(
            "identifier is empty, oversized, or padded",
        ));
    }
    Ok(())
}

fn is_sha256_hex(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
}

